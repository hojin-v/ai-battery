const quote = value => `'${String(value).replace(/'/g, "''")}'`;

// Parameters let the Windows regression test use its own temporary registry key.
export function windowsAutostartCleanupScript({ registryPath, registryName }) {
  return [
    "$ErrorActionPreference = 'Stop'",
    "$dir = Join-Path $env:LOCALAPPDATA 'ai-battery'",
    "$auto = Join-Path $dir 'autostart.ps1'",
    "$hudDir = Join-Path $dir 'hud'",
    "foreach ($p in @($dir, $auto, $hudDir)) { if ((Test-Path -LiteralPath $p) -and ((Get-Item -Force -LiteralPath $p).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw ('Refusing to follow an autostart symlink: ' + $p) } }",
    `$v = (Get-ItemProperty -Path ${quote(registryPath)} -Name ${quote(registryName)} -ErrorAction SilentlyContinue).${registryName}`,
    "$expected = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File \"' + $auto + '\"'",
    "if ($v -and $v -ne $expected) { throw 'AiBatteryHud registry value changed; left it untouched.' }",
    "$ownedFile = $false",
    "if (Test-Path -LiteralPath $auto) {",
    "  $ownedFile = (Get-Content -Raw -LiteralPath $auto).StartsWith('# Generated by: ai-battery hud autostart on')",
    "  if (-not $ownedFile) { throw 'Autostart file changed; left it and its registry value untouched.' }",
    "}",
    `if ($v) { Remove-ItemProperty -Path ${quote(registryPath)} -Name ${quote(registryName)} }`,
    "if ($ownedFile) {",
    "  Remove-Item -LiteralPath $auto -Force",
    "  if (Test-Path -LiteralPath $hudDir) {",
    "    foreach ($name in @('main.ps1', 'controls.ps1', 'dock.ps1', 'native.ps1', 'rendering.ps1', 'snapshot.ps1', 'windowing.ps1', 'ai-battery-hud.ps1')) {",
    "      $file = Join-Path $hudDir $name",
    "      if (Test-Path -LiteralPath $file -PathType Leaf) {",
    "        if ((Get-Item -Force -LiteralPath $file).Attributes -band [IO.FileAttributes]::ReparsePoint) { continue }",
    "        Remove-Item -LiteralPath $file -Force",
    "      }",
    "    }",
    "    if (-not (Get-ChildItem -Force -LiteralPath $hudDir | Select-Object -First 1)) { Remove-Item -LiteralPath $hudDir }",
    "  }",
    "}",
    "if ((Test-Path -LiteralPath $dir) -and -not (Get-ChildItem -Force -LiteralPath $dir | Select-Object -First 1)) { Remove-Item -LiteralPath $dir }"
  ].join("\n");
}
